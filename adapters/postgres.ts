import { Client, types } from "pg";
import type { SqlDatabase, SqlStatement, SqlValue } from "../src/ports.js";

// PostgreSQL returns int8 (COUNT, SUM over integers) as a string to avoid
// precision loss. The other adapters return numbers, and the app is written
// against numbers, so the driver is normalised here rather than at each call.
types.setTypeParser(types.builtins.INT8, (value: string) => Number(value));

/**
 * PostgreSQL through node-postgres. Like the SQLite adapter this is a host
 * driver: the core never imports it.
 */

/**
 * Rewrites `?` placeholders to PostgreSQL's `$1..$n`, leaving anything inside
 * a quoted string or identifier alone. The core's SQL only uses `?` as a
 * binding marker, so this is a straight positional rewrite.
 */
export function toPostgresPlaceholders(sql: string): string {
	let out = "";
	let indexed = 0;
	let quote: "'" | '"' | null = null;

	for (const char of sql) {
		if (quote) {
			out += char;
			if (char === quote) quote = null;
			continue;
		}
		if (char === "'" || char === '"') {
			quote = char;
			out += char;
			continue;
		}
		if (char === "?") {
			indexed += 1;
			out += `$${indexed}`;
			continue;
		}
		out += char;
	}

	return out;
}

/** A schema name is generated by the caller, but quote it anyway. */
function quoteIdent(name: string): string {
	return `"${name.replace(/"/g, '""')}"`;
}

class PostgresStatement implements SqlStatement {
	constructor(
		private readonly client: Client,
		private readonly sql: string,
		private readonly values: readonly SqlValue[] = [],
	) {}

	bind(...values: SqlValue[]): SqlStatement {
		return new PostgresStatement(this.client, this.sql, values);
	}

	async first<T = Record<string, unknown>>(): Promise<T | null> {
		const { rows } = await this.client.query(this.sql, this.values as unknown[]);
		return (rows[0] ?? null) as T | null;
	}

	async all<T = Record<string, unknown>>(): Promise<{ results: T[] }> {
		const { rows } = await this.client.query(this.sql, this.values as unknown[]);
		return { results: rows as T[] };
	}

	async run(): Promise<{ meta: { changes: number } }> {
		const result = await this.client.query(this.sql, this.values as unknown[]);
		return { meta: { changes: result.rowCount ?? 0 } };
	}
}

export interface PostgresDatabase extends SqlDatabase {
	close(): Promise<void>;
}

export interface PostgresOptions {
	connectionString: string;
	/**
	 * When set, the adapter creates this schema and points `search_path` at it,
	 * which is how the test suite isolates one file from another in a shared
	 * database.
	 */
	schema?: string;
}

export async function openPostgresDatabase({
	connectionString,
	schema,
}: PostgresOptions): Promise<PostgresDatabase> {
	const client = new Client({ connectionString });
	await client.connect();

	if (schema) {
		await client.query(`CREATE SCHEMA IF NOT EXISTS ${quoteIdent(schema)}`);
		await client.query(`SET search_path TO ${quoteIdent(schema)}`);
	}

	return {
		prepare(sql: string): SqlStatement {
			return new PostgresStatement(client, toPostgresPlaceholders(sql));
		},

		async exec(sql: string): Promise<void> {
			// No parameters, so node-postgres uses the simple protocol and a
			// whole migration file runs as one implicit transaction.
			await client.query(sql);
		},

		async now(): Promise<string> {
			const { rows } = await client.query<{ now: string }>(
				`SELECT to_char((now() AT TIME ZONE 'utc'), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') AS now`,
			);
			const row = rows[0];
			if (!row) throw new Error("could not read the database clock");
			return row.now;
		},

		async close(): Promise<void> {
			await client.end();
		},
	};
}