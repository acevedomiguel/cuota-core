import { Pool, types } from "pg";
import type { SqlDatabase, SqlStatement, SqlValue } from "../src/ports.js";
import { makeStrictClock } from "./clock.js";

// PostgreSQL returns int8 (COUNT, SUM over integers) as a string to avoid
// precision loss. The other adapters return numbers, and the app is written
// against numbers, so the driver is normalised here rather than at each call.
types.setTypeParser(types.builtins.INT8, (value: string) => Number(value));

/**
 * PostgreSQL through node-postgres. Like the SQLite adapter this is a host
 * driver: the core never imports it.
 */

/**
 * Rewrites `?` placeholders to PostgreSQL's `$1..$n`, leaving anything inside
 * a quoted string or identifier alone. The core's SQL only uses `?` as a
 * binding marker, so this is a straight positional rewrite.
 */
export function toPostgresPlaceholders(sql: string): string {
	let out = "";
	let indexed = 0;
	let quote: "'" | '"' | null = null;

	for (const char of sql) {
		if (quote) {
			out += char;
			if (char === quote) quote = null;
			continue;
		}
		if (char === "'" || char === '"') {
			quote = char;
			out += char;
			continue;
		}
		if (char === "?") {
			indexed += 1;
			out += `$${indexed}`;
			continue;
		}
		out += char;
	}

	return out;
}

/** The slice of a Pool or a PoolClient this adapter needs. */
interface Queryable {
	query(text: string, values?: unknown[]): Promise<{ rows: unknown[]; rowCount: number | null }>;
}

/** A schema name is generated by the caller, but validate it anyway. */
function checkedSchema(name: string): string {
	if (!/^[a-z_][a-z0-9_]*$/.test(name)) {
		throw new Error(`schema name must be a plain identifier, got ${JSON.stringify(name)}`);
	}
	return name;
}

class PostgresStatement implements SqlStatement {
	constructor(
		private readonly connection: Queryable,
		private readonly sql: string,
		private readonly values: readonly SqlValue[] = [],
	) {}

	bind(...values: SqlValue[]): SqlStatement {
		return new PostgresStatement(this.connection, this.sql, values);
	}

	async first<T = Record<string, unknown>>(): Promise<T | null> {
		const { rows } = await this.connection.query(this.sql, this.values as unknown[]);
		return (rows[0] ?? null) as T | null;
	}

	async all<T = Record<string, unknown>>(): Promise<{ results: T[] }> {
		const { rows } = await this.connection.query(this.sql, this.values as unknown[]);
		return { results: rows as T[] };
	}

	async run(): Promise<{ meta: { changes: number } }> {
		const result = await this.connection.query(this.sql, this.values as unknown[]);
		return { meta: { changes: result.rowCount ?? 0 } };
	}
}

class PostgresDatabase implements SqlDatabase {
	/** Strictly increasing view of the database clock (see clock.ts). */
	private readonly nowStrict: () => Promise<string>;

	constructor(
		private readonly connection: Queryable,
		private readonly pool: Pool | null,
		private readonly onClose: () => Promise<void>,
	) {
		this.nowStrict = makeStrictClock(async () => {
			const { rows } = await this.connection.query(
				`SELECT to_char((now() AT TIME ZONE 'utc'), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') AS now`,
			);
			const row = rows[0] as { now: string } | undefined;
			if (!row) throw new Error("could not read the database clock");
			return row.now;
		});
	}

	prepare(sql: string): SqlStatement {
		return new PostgresStatement(this.connection, toPostgresPlaceholders(sql));
	}

	async exec(sql: string): Promise<void> {
		// No parameters, so node-postgres uses the simple protocol and a whole
		// migration file runs as one implicit transaction.
		await this.connection.query(sql);
	}

	async now(): Promise<string> {
		return this.nowStrict();
	}

	async withTransaction<T>(work: (db: SqlDatabase) => Promise<T>): Promise<T> {
		if (!this.pool) throw new Error("nested transactions are not supported");

		const client = await this.pool.connect();
		try {
			await client.query("BEGIN");
			const result = await work(new PostgresDatabase(client, null, async () => {}));
			await client.query("COMMIT");
			return result;
		} catch (error) {
			await client.query("ROLLBACK").catch(() => {});
			throw error;
		} finally {
			client.release();
		}
	}

	async close(): Promise<void> {
		await this.onClose();
	}
}

export interface PostgresDatabaseHandle extends SqlDatabase {
	close(): Promise<void>;
}

export interface PostgresOptions {
	connectionString: string;
	/**
	 * When set, the adapter creates this schema and points the connection's
	 * `search_path` at it, which is how the test suite isolates one file from
	 * another in a shared database.
	 */
	schema?: string;
}

export async function openPostgresDatabase({
	connectionString,
	schema,
}: PostgresOptions): Promise<PostgresDatabaseHandle> {
	const pool = new Pool({
		connectionString,
		// `search_path` is set per connection, so it holds for pooled clients
		// and for the dedicated client a transaction checks out.
		...(schema ? { options: `-c search_path=${checkedSchema(schema)}` } : {}),
	});

	// A pool hands out connections lazily, but a broken connection string should
	// fail here rather than on the first request.
	const probe = await pool.connect();
	try {
		if (schema) {
			await probe.query(`CREATE SCHEMA IF NOT EXISTS ${checkedSchema(schema)}`);
		}
	} finally {
		probe.release();
	}

	return new PostgresDatabase(pool as unknown as Queryable, pool, () => pool.end());
}